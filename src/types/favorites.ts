import type { MediaItem } from '@/api/types'

/**
 * Категория избранного: «Смотрю», «Посмотреть», «Новый год». Живёт только на
 * клиенте, к TMDB отношения не имеет — потому и лежит не в `api/`.
 *
 * Категория, а не метка: на тайтл их приходится ровно одна. Многозначность
 * стоила бы полосы чипов с мультивыбором, фильтрации по ИЛИ и отдельного
 * менеджера реестра — при том, что в реальной коллекции второй метки почти
 * никогда не бывает.
 */
export interface Category {
  /**
   * Короткий идентификатор вида `c1`. Короткий, потому что уходит в путь:
   * `/favorites/c1` читается, UUID — нет.
   *
   * Идентификатор, а не имя, потому что категорию можно переименовать: с именем
   * в качестве ключа пришлось бы переписать все записи коллекции, с id — одну.
   */
  id: string
  name: string
}

/**
 * Тайтл, который никуда не разложили. Значение хранится в записи как есть — не
 * пустая строка и не `null`, чтобы одно и то же значение годилось и для
 * хранилища, и для адреса `/favorites/none`, и не пришлось переводить между
 * представлениями. Совпасть с настоящим id не может: те всегда вида `c<число>`.
 */
export const UNCATEGORIZED = 'none'

/**
 * Запись избранного: нормализованный тайтл плюс категория. Наследуется от
 * `MediaItem`, поэтому `MediaCard` и `MediaGrid`, которые принимают
 * `MediaItem[]`, работают с избранным без изменений.
 */
export interface FavoriteItem extends MediaItem {
  /** Всегда непустой: либо id категории, либо `UNCATEGORIZED`. */
  categoryId: string
}
