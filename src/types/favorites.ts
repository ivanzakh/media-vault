import type { MediaItem } from '@/api/types'

/**
 * Пользовательская метка: «Фильмы на Рождество», «marvel», «космос». Живёт
 * только на клиенте, к TMDB отношения не имеет — потому и лежит не в `api/`.
 */
export interface Tag {
  /**
   * Короткий идентификатор вида `t1`. Короткий, потому что уходит в строку
   * запроса: `/favorites?tags=t1|t3` читается, UUID — нет.
   *
   * Идентификатор, а не имя, потому что метку можно переименовать: с именем в
   * качестве ключа пришлось бы переписать все записи коллекции, с id — одну.
   */
  id: string
  name: string
}

/**
 * Запись избранного: нормализованный тайтл плюс метки. Наследуется от
 * `MediaItem`, поэтому `MediaCard` и `MediaGrid`, которые принимают
 * `MediaItem[]`, работают с избранным без изменений.
 */
export interface FavoriteItem extends MediaItem {
  tagIds: string[]
}
